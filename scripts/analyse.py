"""Run the documented SQL and export evidence plus a concise trend report."""
import json
from pathlib import Path

from scripts.project import ROOT, connect


def main():
    connection = connect()
    results = {}
    try:
        with connection.cursor() as cursor:
            for name in ("summary", "daily", "peak_windows", "patterns", "gaps"):
                cursor.execute((ROOT / f"db/queries/{name}.sql").read_text())
                columns = [column.name for column in cursor.description]
                results[name] = [dict(zip(columns, row)) for row in cursor.fetchall()]
    finally:
        connection.close()
    output = ROOT / "docs/evidence"
    output.mkdir(parents=True, exist_ok=True)
    (output / "analysis.json").write_text(json.dumps(results, indent=2, default=str) + "\n", encoding="utf-8")
    summary = results["summary"][0]
    days = [day for day in results["daily"] if day["cpu_samples"] >= 200]
    low = min(days, key=lambda row: row["mean_reported_cpu_percent"])
    peak = max(days, key=lambda row: row["mean_reported_cpu_percent"])
    report = f"""# Observed utilization trends

Generated by `python -m scripts.analyse` from the stored historical data.
All averages weight accepted snapshots equally, rather than elapsed time.
No missing periods are filled. CPU values are reported percentages, with
unconfirmed collection semantics. Source timezone is unconfirmed.

- Snapshots: {summary['snapshots']:,}; {summary['first_timestamp']} to {summary['last_timestamp']}.
- Mean reported CPU: {summary['mean_reported_cpu_percent']:.2f}%; range {summary['min_reported_cpu_percent']:.2f}–{summary['max_reported_cpu_percent']:.2f}%.
- CPU-present snapshots: {summary['cpu_samples']:,}; missing: {summary['missing_cpu_samples']:,}.
- Reported CPU above 100%: {summary['cpu_above_100_samples']:,}; exactly zero: {summary['zero_reported_cpu_samples']:,}.
- Mean running-job count: {summary['mean_running_jobs']:.2f}; mean queued-job count: {summary['mean_queued_jobs']:.2f}; maximum queued count: {summary['max_queued_jobs']:,}.
- Highest daily mean among days with at least 200 CPU samples: {peak['day']}, {peak['mean_reported_cpu_percent']:.2f}% ({peak['cpu_samples']} CPU samples).
- Lowest daily mean under that same coverage rule: {low['day']}, {low['mean_reported_cpu_percent']:.2f}% ({low['cpu_samples']} CPU samples).
- Largest accepted-snapshot gap: {results['gaps'][0]['gap']}, between {results['gaps'][0]['previous']} and {results['gaps'][0]['next']}.

The 200-sample daily threshold is a reporting choice, not a guarantee of full
daily coverage. A usual five-minute day would have 288 snapshots. See the JSON
for hourly/daily/weekly peak rankings, sample counts, and all 168 weekday/hour
combinations. These combine years with changing cluster capacity and data
coverage; they are descriptive and cannot establish causes or stable workload
seasonality. Use the dashboard date filter to compare narrower periods.

Queue size measures backlog, not waiting time. Running-job counts measure
occupancy, not completed-job throughput. A zero reported CPU value does not
prove that hardware was idle. No per-node usage, job identifiers, users, memory,
job completions or job arrival times exist in this dataset.

## Reproduce

Run `python -m scripts.project verify`, then `python -m scripts.analyse`.
SQL sources are in `db/queries/`; complete results are in
[`evidence/analysis.json`](evidence/analysis.json). Dashboard series use the same
measures with a selected date range and explicit aggregation interval.
"""
    (ROOT / "docs/analysis.md").write_text(report, encoding="utf-8")
    print(report)


if __name__ == "__main__":
    main()
